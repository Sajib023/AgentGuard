"""Start AgentGuard automatically at login/boot.

* Windows: per-user Task Scheduler task (``schtasks /SC ONLOGON``), falling
  back to the ``HKCU\\...\\Run`` registry key when task creation is denied
  (common for non-admin accounts). Neither path needs elevation for the
  Run key; both launch a tiny ``boot_start.pyw`` with ``pythonw.exe`` so no
  console window appears.
* Linux: ``systemd --user`` unit (the bash installer still owns creation;
  this module can report on / disable it).
* macOS: not managed here (use ``agentguard serve --daemon`` from a login item).
"""

from __future__ import annotations

import contextlib
import subprocess
import sys
from pathlib import Path

from . import oscompat

TASK_NAME = "AgentGuard"
RUN_VALUE = "AgentGuard"
_RUN_KEY = r"Software\Microsoft\Windows\CurrentVersion\Run"

BOOT_SCRIPT_TEMPLATE = '''\
"""AgentGuard login launcher (generated by `agentguard autostart enable`)."""
import os
import sys
import json
import urllib.request

HOME = {home!r}
CONFIG = {config!r}
PORT = {port!r}
MODEL = {model!r}
OLLAMA = {ollama!r}

os.environ.setdefault("AGENTGUARD_HOME", HOME)
if CONFIG:
    os.environ.setdefault("AGENTGUARD_CONFIG", CONFIG)
os.environ.setdefault("PYTHONUTF8", "1")

# pythonw has no stdout/stderr: route everything to the service log
_log = open(os.path.join(HOME, "agentguard.log"), "a", encoding="utf-8", buffering=1)
sys.stdout = sys.stderr = _log

# Best-effort Ollama warm-up (keeps llama-guard resident for 24h)
if MODEL and OLLAMA:
    try:
        body = json.dumps({{"model": MODEL, "prompt": "", "keep_alive": "24h"}}).encode()
        req = urllib.request.Request(OLLAMA.rstrip("/") + "/api/generate", data=body,
                                     headers={{"Content-Type": "application/json"}})
        urllib.request.urlopen(req, timeout=30).read()
    except Exception as exc:
        print(f"[agentguard] ollama warm-up skipped: {{exc}}")

argv = ["agentguard", "serve"]
if CONFIG:
    argv += ["--config", CONFIG]
if PORT:
    argv += ["--port", str(PORT)]
sys.argv = argv
from agentguard.cli import main
sys.exit(main())
'''


def _home() -> Path:
    from .cli import _agentguard_home

    return _agentguard_home()


def _hidden() -> dict:
    return {"creationflags": oscompat.CREATE_NO_WINDOW} if oscompat.IS_WINDOWS else {}


def write_boot_script(config: str | None, port: int | None, model: str | None = None,
                      ollama: str | None = None) -> Path:
    home = _home()
    script = home / "boot_start.pyw"
    script.write_text(
        BOOT_SCRIPT_TEMPLATE.format(
            home=str(home), config=str(Path(config).expanduser().resolve()) if config else "",
            port=int(port) if port else None, model=model or "", ollama=ollama or "",
        ),
        encoding="utf-8",
    )
    return script


def _launch_command(script: Path) -> str:
    return f'"{oscompat.background_python()}" "{script}"'


# --------------------------------------------------------------------------- windows
def _win_task_exists() -> bool:
    try:
        r = subprocess.run(["schtasks", "/Query", "/TN", TASK_NAME], capture_output=True, text=True,
                           timeout=15, **_hidden())
        return r.returncode == 0
    except Exception:
        return False


def _win_run_key_value() -> str | None:
    with contextlib.suppress(Exception):
        import winreg  # type: ignore

        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, _RUN_KEY) as key:
            return str(winreg.QueryValueEx(key, RUN_VALUE)[0])
    return None


def _win_enable(command: str) -> str:
    # 1) Task Scheduler (restarts not supported by schtasks CLI, but survives logoff/logon)
    if len(command) <= 261:
        try:
            r = subprocess.run(
                ["schtasks", "/Create", "/TN", TASK_NAME, "/SC", "ONLOGON", "/RL", "LIMITED",
                 "/TR", command, "/F"],
                capture_output=True, text=True, timeout=30, **_hidden(),
            )
            if r.returncode == 0:
                return "task-scheduler"
        except Exception:
            pass
    # 2) HKCU Run key — always allowed for the current user
    import winreg  # type: ignore

    with winreg.CreateKey(winreg.HKEY_CURRENT_USER, _RUN_KEY) as key:
        winreg.SetValueEx(key, RUN_VALUE, 0, winreg.REG_SZ, command)
    return "registry-run-key"


def _win_disable() -> list[str]:
    removed: list[str] = []
    if _win_task_exists():
        with contextlib.suppress(Exception):
            subprocess.run(["schtasks", "/Delete", "/TN", TASK_NAME, "/F"], capture_output=True,
                           timeout=15, **_hidden())
            removed.append("task-scheduler")
    if _win_run_key_value() is not None:
        with contextlib.suppress(Exception):
            import winreg  # type: ignore

            with winreg.OpenKey(winreg.HKEY_CURRENT_USER, _RUN_KEY, 0, winreg.KEY_SET_VALUE) as key:
                winreg.DeleteValue(key, RUN_VALUE)
            removed.append("registry-run-key")
    return removed


# --------------------------------------------------------------------------- linux
def _systemd_user(*args: str) -> subprocess.CompletedProcess | None:
    try:
        return subprocess.run(["systemctl", "--user", *args], capture_output=True, text=True, timeout=15)
    except Exception:
        return None


# --------------------------------------------------------------------------- public API
def enable(config: str | None = None, port: int | None = None, model: str | None = None,
           ollama: str | None = None) -> str:
    """Register auto-start; returns the method used."""
    if oscompat.IS_WINDOWS:
        script = write_boot_script(config, port, model, ollama)
        return _win_enable(_launch_command(script))
    if sys.platform.startswith("linux"):
        unit = Path.home() / ".config" / "systemd" / "user" / "agentguard.service"
        if unit.is_file():
            r = _systemd_user("enable", "agentguard.service")
            if r is not None and r.returncode == 0:
                return "systemd-user"
        raise RuntimeError("no systemd user unit found — run ./install.sh to create it")
    raise RuntimeError(f"autostart is not managed by the CLI on {sys.platform}")


def disable() -> list[str]:
    if oscompat.IS_WINDOWS:
        removed = _win_disable()
        with contextlib.suppress(FileNotFoundError):
            (_home() / "boot_start.pyw").unlink()
        return removed
    removed: list[str] = []
    r = _systemd_user("disable", "--now", "agentguard.service")
    if r is not None and r.returncode == 0:
        removed.append("systemd-user")
    return removed


def status() -> dict:
    if oscompat.IS_WINDOWS:
        return {
            "platform": "windows",
            "task_scheduler": _win_task_exists(),
            "registry_run_key": _win_run_key_value(),
            "boot_script": str(_home() / "boot_start.pyw"),
        }
    r = _systemd_user("is-enabled", "agentguard.service")
    return {
        "platform": sys.platform,
        "systemd_user": (r.stdout.strip() if r is not None else "unavailable") or "disabled",
    }
